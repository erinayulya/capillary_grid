function plotNetwork(N_cols, N_rows)

%% ============================================================
% Проверка входных данных
% ============================================================

if ~isscalar(N_cols) || ...
        ~isscalar(N_rows) || ...
        ~isfinite(N_cols) || ...
        ~isfinite(N_rows) || ...
        N_cols < 1 || ...
        N_rows < 1 || ...
        N_cols ~= round(N_cols) || ...
        N_rows ~= round(N_rows)

    error( ...
        'N_cols и N_rows должны быть положительными целыми числами.');

end


N_cols = round(N_cols);
N_rows = round(N_rows);


%% ============================================================
% Создание окна
% ============================================================

figure( ...
    'Name', 'Схема сети', ...
    'NumberTitle', 'off', ...
    'Position', [500 150 750 600]);

ax = axes;

hold(ax, 'on');


%% ============================================================
% Горизонтальные капилляры
% ============================================================

% N_rows горизонтальных рядов.
%
% Каждый ряд содержит N_cols + 1 капилляров.
%
% Горизонтальные ряды находятся на уровнях:
%
% y = 0, 1, ..., N_rows-1

for i = 0:N_rows-1

    for j = 0:N_cols

        plot(ax, ...
            [j, j+1], ...
            [i, i], ...
            'Color', 'k', ...
            'LineWidth', 3);

    end

end


%% ============================================================
% Вертикальные капилляры
% ============================================================

% N_cols вертикальных капилляров.
%
% Они расположены в точках:
%
% x = 1, 2, ..., N_cols
%
% Каждый вертикальный капилляр проходит:
%
% y = -1 ... N_rows
%
% Поэтому матрица Av имеет размер:
%
% (N_rows + 1) × N_cols

for j = 1:N_cols

    plot(ax, ...
        [j, j], ...
        [-1, N_rows], ...
        'Color', 'k', ...
        'LineWidth', 3);

end


%% ============================================================
% Узлы
% ============================================================

% Узлы горизонтальных рядов

for i = 0:N_rows-1

    for j = 0:N_cols

        plot(ax, ...
            j, i, ...
            'ko', ...
            'MarkerFaceColor', 'k', ...
            'MarkerSize', 6);

    end

end


%% ============================================================
% Входные точки слева
% ============================================================

for i = 0:N_rows-1

    plot(ax, ...
        0, i, ...
        'ro', ...
        'MarkerFaceColor', 'r', ...
        'MarkerSize', 9);

end


%% ============================================================
% Настройка осей
% ============================================================

axis(ax, 'equal');

% Добавляем небольшой запас вокруг сети,
% чтобы она полностью помещалась в области осей.

xlim(ax, [-0.7, N_cols + 1.7]);

ylim(ax, [-1.7, N_rows + 0.7]);

xlabel(ax, 'x', ...
    'FontSize', 14);

ylabel(ax, 'y', ...
    'FontSize', 14);

title(ax, ...
    sprintf('Схема сети: N_{rows} = %d, N_{cols} = %d', ...
    N_rows, N_cols), ...
    'FontSize', 16);

grid(ax, 'on');

box(ax, 'on');

set(ax, ...
    'FontSize', 12);

hold(ax, 'off');

end