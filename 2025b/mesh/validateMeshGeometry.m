function validateMeshGeometry(Ah, Av)
%VALIDATEMESHGEOMETRY Check positive areas (m^2) and rectangular network sizes.
% Ah: nRows-by-(nCols+1); Av: (nRows+1)-by-nCols. Does not modify inputs.
validateattributes(Ah,{'numeric'},{'real','2d','nonempty','finite','positive'}, ...
    mfilename,'Ah');
validateattributes(Av,{'numeric'},{'real','2d','nonempty','finite','positive'}, ...
    mfilename,'Av');
if size(Ah,1) < 1 || size(Av,2) < 1 || ...
        size(Av,1) ~= size(Ah,1)+1 || size(Ah,2) ~= size(Av,2)+1
    error('validateMeshGeometry:SizeMismatch', ...
        ['Размеры матриц не согласованы: Ah — %d × %d, Av — %d × %d.\n' ...
         'Требуется size(Av,1) = size(Ah,1)+1 и size(Ah,2) = size(Av,2)+1.'], ...
        size(Ah,1),size(Ah,2),size(Av,1),size(Av,2));
end
end
